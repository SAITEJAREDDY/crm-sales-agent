def iso_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def normalize_record(record: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Apply defaults and deterministic fallbacks, returning warnings."""
    out = dict(record)
    warnings: list[str] = []

    out.setdefault("enablement_data_version", ENABLEMENT_DATA_VERSION)
    out.setdefault("scored_at", iso_now())
    out.setdefault("partner_managed_status", False)
    out.setdefault("certifications_held", [])
    out.setdefault("learner_roster", [])

    tier = out.get("company_tier") or ("Enterprise" if float(out.get("deal_amount", 0) or 0) > 500_000 else "Mid-Market")
    defaults = {
        "Enterprise": {"licensed_users": 450, "trained_users": 95, "azure_annual_consumption": 180_000.0},
        "Mid-Market": {"licensed_users": 120, "trained_users": 22, "azure_annual_consumption": 65_000.0},
        "SMB": {"licensed_users": 40, "trained_users": 8, "azure_annual_consumption": 24_000.0},
    }.get(tier, {"licensed_users": 80, "trained_users": 16, "azure_annual_consumption": 45_000.0})

    for field, fallback in defaults.items():
        if out.get(field) in (None, ""):
            out[field] = fallback
            warnings.append(f"{field} missing; defaulted from {tier} profile")

    out["licensed_users"] = int(max(0, out.get("licensed_users") or 0))
    out["trained_users"] = int(max(0, out.get("trained_users") or 0))
    out["azure_annual_consumption"] = float(max(0.0, out.get("azure_annual_consumption") or 0.0))
    out["enablement_coverage_pct"] = (
        round(out["trained_users"] * 100 / out["licensed_users"], 2)
        if out["licensed_users"] else 0.0
    )
    out["skills_gap_risk_score"] = int(max(0, min(100, out.get("skills_gap_risk_score") or 0)))

    if out.get("attendance_rate_pct") is not None:
        out["attendance_rate_pct"] = float(max(0.0, min(100.0, out["attendance_rate_pct"])))
    if out.get("days_inactive") is not None:
        out["days_inactive"] = int(max(0, out["days_inactive"]))
    if out.get("days_to_renewal") is not None:
        out["days_to_renewal"] = int(max(0, out["days_to_renewal"]))

    normalized_roster = []
    for learner in out.get("learner_roster") or []:
        normalized_roster.append({
            "learner_id": str(learner.get("learner_id", "")),
            "role_persona": str(learner.get("role_persona", "Data Engineer")),
            "courses_completed": list(learner.get("courses_completed") or []),
            "certifications": list(learner.get("certifications") or []),
        })
    out["learner_roster"] = normalized_roster

    return out, warnings


def validate_record(record: dict[str, Any]) -> tuple[bool, list[str]]:
    errors: list[str] = []
    for field in ("company_slug", "deal_slug"):
        if not isinstance(record.get(field), str) or not record[field].strip():
            errors.append(f"{field} is required")

    numeric_ranges = {
        "licensed_users": (int, 0, None),
        "trained_users": (int, 0, None),
        "enablement_coverage_pct": ((int, float), 0.0, 100.0),
        "skills_gap_risk_score": (int, 0, 100),
        "azure_annual_consumption": ((int, float), 0.0, None),
    }
    for field, (types, low, high) in numeric_ranges.items():
        value = record.get(field)
        if not isinstance(value, types):
            errors.append(f"{field} must be {types}")
            continue
        if value < low or (high is not None and value > high):
            errors.append(f"{field} outside allowed range")

    try:
        datetime.fromisoformat(str(record.get("scored_at", "")).replace("Z", "+00:00"))
    except Exception:
        errors.append("scored_at must be ISO timestamp")

    if not isinstance(record.get("partner_managed_status"), bool):
        errors.append("partner_managed_status must be boolean")

    if not isinstance(record.get("learner_roster"), list):
        errors.append("learner_roster must be a list")
    else:
        for i, learner in enumerate(record["learner_roster"]):
            for field in ("learner_id", "role_persona"):
                if not isinstance(learner.get(field), str) or not learner[field].strip():
                    errors.append(f"learner_roster[{i}].{field} is required")
            for field in ("courses_completed", "certifications"):
                if not isinstance(learner.get(field), list):
                    errors.append(f"learner_roster[{i}].{field} must be list")

    return not errors, errors


def normalize_and_validate(record: dict[str, Any]) -> tuple[dict[str, Any], list[str], list[str]]:
    normalized, warnings = normalize_record(record)
    valid, errors = validate_record(normalized)
    return normalized, warnings, ([] if valid else errors)
